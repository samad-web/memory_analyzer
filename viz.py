r"""The dashboard's visual vocabulary, in one place for both front ends.

There are two dashboards -- a Qt window and a web page -- and they must not
drift apart. Everything that decides what a chart looks like lives here: the
categorical order, the status colours, the surfaces, and the formatters. The Qt
charts read these constants directly; the web page gets the same values as CSS
custom properties generated by ``theme_css()``, so a colour is changed once.

Why these particular hues
-------------------------
The tile's own accents (``#4cc2ff`` CPU, ``#a78bfa`` RAM, ``#4ade80`` GPU,
``#fbbf24`` FAN) are kept for the machine-health readouts, where each sits on
its own labelled row and is never asked to be told apart from its neighbours.
As a *categorical* palette they fail: every one of them is tuned to glow on a
dark tile, which puts them above the lightness band, and blue against purple
comes out at a deuteranopia Delta-E of 7.0 -- inside the floor band where two
series beside each other in a legend stop being distinguishable.

So series colour uses a separate, validated order. Checked with the data-viz
validator against this dashboard's actual surface (``#0e1119``, darker than the
reference default, which changes the contrast result):

    8 slots, adjacent pairs : worst CVD Delta-E 8.4 (protan), normal-vision 19.3
    3 slots, all pairs      : worst CVD Delta-E 9.4, normal-vision 20.9

Both clear the >= 8 CVD target and the >= 15 normal-vision floor. Slots are
assigned in fixed order and never cycled -- a ninth series folds into "other"
rather than reusing slot 1, because a repeated hue reads as a repeated entity.
"""

from __future__ import annotations

# -- surfaces and ink ------------------------------------------------------
# Taken from the tile so the two windows look like one product.

SURFACE = "#0e1119"        # window background
SURFACE_CARD = "#141720"   # raised card
SURFACE_RAISED = "#1a1e2a" # control background
BORDER = "#262b38"
BORDER_SOFT = "#1e2330"

INK = "#e6eaf2"            # primary text
INK_DIM = "#9aa3b5"        # secondary text
INK_MUTED = "#6b7486"      # axis labels, captions
GRID = "#1c2029"           # recessive gridlines

# -- categorical series ----------------------------------------------------
# Fixed order. Index 0 first, always.

SERIES = (
    "#3987e5",  # 1 blue
    "#d95926",  # 2 orange
    "#199e70",  # 3 aqua
    "#c98500",  # 4 yellow
    "#d55181",  # 5 magenta
    "#008300",  # 6 green
    "#9085e9",  # 7 violet
    "#e66767",  # 8 red
)

# Model families get stable slots rather than first-come assignment, so Opus is
# the same colour in every chart on every day -- colour follows the entity, not
# its rank in today's data.
MODEL_COLORS = {
    "opus": SERIES[0],
    "sonnet": SERIES[2],
    "haiku": SERIES[3],
    "fable": SERIES[4],
    "other": SERIES[1],
    "unknown": INK_MUTED,
}

# -- status ----------------------------------------------------------------
# Reserved. Never reused as a series colour, and always shipped with a text
# label beside the swatch, never colour alone.

STATUS = {
    "needs_input": "#ff9500",  # blocked on a person
    "working": "#60a5fa",      # running
    "done": "#4ade80",         # finished
    "offline": "#6b7486",      # not reporting
}
STATUS_LABEL = {
    "needs_input": "needs you",
    "working": "working",
    "done": "done",
    "offline": "offline",
}

# -- sequential ------------------------------------------------------------
# One hue, light to dark, for continuous magnitude (the hour-of-day heat row).
# Reversed for a dark surface: the pale end means "near zero" and is allowed to
# recede toward the background.

SEQUENTIAL = (
    "#0d366b", "#104281", "#184f95", "#1c5cab",
    "#256abf", "#2a78d6", "#3987e5", "#5598e7",
)

# -- machine health --------------------------------------------------------
# The tile's accents, kept deliberately (see the module docstring).

HEALTH = {
    "cpu": "#4cc2ff",
    "ram": "#a78bfa",
    "gpu": "#4ade80",
    "fan": "#fbbf24",
    "temp_warm": "#fbbf24",
    "temp_hot": "#f87171",
}

# Above these a temperature reading is tinted rather than left as plain ink.
TEMP_WARM = 75.0
TEMP_HOT = 88.0


def series_color(index: int) -> str:
    """Slot ``index``, clamped rather than wrapped.

    Wrapping would hand series 9 the same hue as series 1, which reads as the
    same entity appearing twice. Callers that can exceed eight series fold the
    tail into one "other" bucket instead.
    """
    if index < 0:
        return SERIES[0]
    return SERIES[min(index, len(SERIES) - 1)]


def model_color(family: str) -> str:
    return MODEL_COLORS.get((family or "unknown").lower(), SERIES[1])


def status_color(state: str) -> str:
    return STATUS.get((state or "").lower(), INK_MUTED)


def temp_color(value: float | None) -> str:
    if value is None:
        return INK_DIM
    if value >= TEMP_HOT:
        return HEALTH["temp_hot"]
    if value >= TEMP_WARM:
        return HEALTH["temp_warm"]
    return INK_DIM


def sequential_color(fraction: float) -> str:
    """A step from the sequential ramp for ``fraction`` in 0..1."""
    if fraction <= 0:
        return SEQUENTIAL[0]
    index = int(round(max(0.0, min(1.0, fraction)) * (len(SEQUENTIAL) - 1)))
    return SEQUENTIAL[index]


# -- formatters ------------------------------------------------------------
# Shared so a number is spelled the same way on the tile, in the Qt window and
# on the web page.


def fmt_tokens(n) -> str:
    try:
        n = float(n or 0)
    except (TypeError, ValueError):
        return "0"
    if n >= 1_000_000_000:
        return f"{n / 1_000_000_000:.2f}B"
    if n >= 1_000_000:
        return f"{n / 1_000_000:.1f}M"
    if n >= 1_000:
        return f"{n / 1_000:.0f}K"
    return str(int(n))


def fmt_cost(c) -> str:
    try:
        return f"${float(c or 0):,.2f}"
    except (TypeError, ValueError):
        return "$0.00"


def fmt_duration(s) -> str:
    if s is None:
        return "--"
    try:
        s = float(s)
    except (TypeError, ValueError):
        return "--"
    if s < 1:
        return "<1s"
    if s < 60:
        return f"{s:.0f}s"
    if s < 3600:
        return f"{s / 60:.0f}m"
    if s < 86400:
        return f"{s / 3600:.1f}h"
    return f"{s / 86400:.1f}d"


def fmt_ago(seconds) -> str:
    if seconds is None:
        return "--"
    try:
        seconds = max(0.0, float(seconds))
    except (TypeError, ValueError):
        return "--"
    if seconds < 45:
        return "just now"
    if seconds < 3600:
        return f"{seconds / 60:.0f}m ago"
    if seconds < 86400:
        return f"{seconds / 3600:.0f}h ago"
    return f"{seconds / 86400:.0f}d ago"


def fmt_int(n) -> str:
    try:
        return f"{int(n or 0):,}"
    except (TypeError, ValueError):
        return "0"


def clip(text, limit: int = 60) -> str:
    text = " ".join(str(text or "").split())
    if len(text) <= limit:
        return text
    return text[: limit - 1].rstrip() + "…"


# -- web theme -------------------------------------------------------------


def theme_css() -> str:
    """The same constants as CSS custom properties, for the web dashboard.

    Generated rather than hand-maintained: a second copy of the palette in a
    stylesheet is a copy that goes stale.
    """
    lines = [
        "/* Generated by viz.theme_css() -- edit viz.py, not this. */",
        ":root {",
        f"  --surface: {SURFACE};",
        f"  --surface-card: {SURFACE_CARD};",
        f"  --surface-raised: {SURFACE_RAISED};",
        f"  --border: {BORDER};",
        f"  --border-soft: {BORDER_SOFT};",
        f"  --ink: {INK};",
        f"  --ink-dim: {INK_DIM};",
        f"  --ink-muted: {INK_MUTED};",
        f"  --grid: {GRID};",
    ]
    for i, hex_value in enumerate(SERIES, start=1):
        lines.append(f"  --series-{i}: {hex_value};")
    for name, hex_value in STATUS.items():
        lines.append(f"  --status-{name.replace('_', '-')}: {hex_value};")
    for name, hex_value in HEALTH.items():
        lines.append(f"  --health-{name.replace('_', '-')}: {hex_value};")
    for i, hex_value in enumerate(SEQUENTIAL):
        lines.append(f"  --seq-{i}: {hex_value};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def model_color_map() -> dict:
    """Model-family colours for the web page's JS."""
    return dict(MODEL_COLORS)
